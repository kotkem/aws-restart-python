numero1 = int(input("Ingrese el primer número: "))  
numero2 = int(input("Ingrese el segundo número: "))

print(f"Suma: {numero1 + numero2} ")
print(f"Resta: {numero1 - numero2} ")
print(f"Multiplicación: {numero1 * numero2} ")
print(f"División: {numero1 / numero2} ")
print(f"Módulo: {numero1 % numero2} ")
print(f"Potencia: {numero1 ** numero2} ")
print(f"División entera: {numero1 // numero2} ")
print(f"Raíz cuadrada del primer número: {numero1 ** 0.5} ")
print(f"Raíz cuadrada del segundo número: {numero2 ** 0.5} ")
print(f"Valor absoluto del primer número: {abs(numero1)} ")
print(f"Valor absoluto del segundo número: {abs(numero2)} ")
